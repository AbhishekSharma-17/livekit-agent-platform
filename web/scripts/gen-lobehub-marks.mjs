const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ICON_DIR = path.join(root, "node_modules/@lobehub/icons-static-svg/icons");
const OUT = path.join(root, "src/components/shared/lobehub-marks.ts");

/** `{ d, fillRule? }[]` from one monochrome lobehub SVG; throws on anything but plain paths. */
export function parseIcon(svg, file) {
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(`${file}: expected a 24 x 24 viewBox`);
  if (!/<svg[^>]*fill="currentColor"/.test(svg)) throw new Error(`${file}: not a currentColor (monochrome) icon`);
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<title>[^<]*<\/title>/, "");
  const leftover = body.replace(/<path\b[^>]*?(?:\/>|><\/path>)/g, "").trim();
  if (leftover) throw new Error(`${file}: unsupported markup ${leftover.slice(0, 60)}`);
  const rootRule = svg.match(/<svg[^>]*\sfill-rule="(\w+)"/)?.[1];
  const paths = [...body.matchAll(/<path\b([^>]*?)(?:\/>|><\/path>)/g)].map(([, attrs]) => {
    if (/\b(?:fill|opacity|fill-opacity|transform|style)=/.test(attrs.replace(/\bfill-rule=/, "")))
      throw new Error(`${file}: a path carries its own paint or transform`);
    const d = attrs.match(/\sd="([^"]+)"/)?.[1];
    if (!d) throw new Error(`${file}: a path without d`);
    const fillRule = attrs.match(/\sfill-rule="(\w+)"/)?.[1] ?? rootRule;
    return fillRule === "evenodd" ? { d, fillRule: "evenodd" } : { d };
  });
  if (paths.length === 0) throw new Error(`${file}: no paths`);
  return paths;
}

export function render() {
  const entries = Object.entries(LOBEHUB_ICONS).map(([name, { file, title }]) => {
    const svg = readFileSync(path.join(ICON_DIR, `${file}.svg`), "utf8");
    const paths = parseIcon(svg, `${file}.svg`);
    return `export const ${name}: LobehubMark = ${JSON.stringify({ slug: file, title, paths })};`;
  });
  return `${[
    "// Generated by scripts/gen-lobehub-marks.mjs from @lobehub/icons-static-svg (MIT,",
    "// https://github.com/lobehub/lobe-icons). Do not edit by hand: add the icon to",
    "// LOBEHUB_ICONS in the script and rerun it.",
    "",
    "export interface LobehubMark {",
    "  slug: string;",
    "  title: string;",
    '  paths: readonly { d: string; fillRule?: "evenodd" }[];',
    "}",
    "",
    ...entries,
  ].join("\n")}\n`;
}

function main() {
  const next = render();
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf8");
    if (current !== next) {
      console.error("lobehub-marks.ts is out of date: run `node scripts/gen-lobehub-marks.mjs`");
      process.exit(1);
    }
    console.log("lobehub-marks.ts matches the package");
    return;
  }
  writeFileSync(OUT, next);
  console.log(`wrote ${path.relative(root, OUT)} (${Object.keys(LOBEHUB_ICONS).length} marks)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
