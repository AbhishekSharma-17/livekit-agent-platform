#!/usr/bin/env node
/**
 * Copies the chosen monochrome marks from `@lobehub/icons-static-svg` (MIT,
 * https://github.com/lobehub/lobe-icons) into `src/components/shared/lobehub-marks.ts`.
 *
 * The package ships only `.svg` files, and the console has no SVG loader, so
 * importing per icon means copying each chosen icon's path data into a typed
 * module: only these marks reach the bundle. Simple Icons stays the first
 * source (`vendor-marks.ts`); this covers the AI vendors it lacks.
 *
 * Usage (from `web/`): `node scripts/gen-lobehub-marks.mjs` to write the file,
 * `--check` to fail when it no longer matches the package
 * (`tests/vendor-marks.test.tsx` runs the check).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

